import { readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createSourceScope, sourceAllowed } from './lib/source-scope.mjs';

export const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const TIME_ZONE = 'America/New_York';

/**
 * Read runtime settings without requiring credentials or an external database.
 * @param {Object} env Environment variable mapping.
 * @return {Object} Validated local server and crawler settings.
 */
export function readConfig(env = process.env) {
  const dataDir = path.resolve(env.CMUEVENTS_DATA_DIR || path.join(ROOT, 'var'));
  mkdirSync(dataDir, { recursive: true });
  return {
    dataDir, databasePath: path.join(dataDir, 'events.sqlite'),
    host: env.HOST || '127.0.0.1', port: Number(env.PORT || 3000),
    concurrency: Math.max(1, Math.min(12, Number(env.CMUEVENTS_CONCURRENCY) || 6)),
    autoRefresh: env.CMUEVENTS_AUTO_REFRESH !== '0',
    publicRendering: env.CMUEVENTS_RENDER_PUBLIC === '1',
    refreshTickMs: 15 * 60 * 1000,
    lookBackDays: 30, lookAheadDays: 365,
    sourceScope: createSourceScope(JSON.parse(readFileSync(path.join(ROOT, 'config/source-scope.json'), 'utf8'))),
  };
}

/**
 * Load the complete catalog-to-adapter mapping generated by the planning tool.
 * @param {string} filename Optional plan file used by tests and maintenance.
 * @return {Array<Object>} Every source plan, including covered and limited sources.
 */
export function loadPlans(filename = path.join(ROOT, 'config/source-plans.json')) {
  const document = JSON.parse(readFileSync(filename, 'utf8'));
  if (!Array.isArray(document.plans)) throw new Error('Source plans must contain a plans array. Run npm run plan.');
  const sourceScope = createSourceScope(JSON.parse(readFileSync(path.join(ROOT, 'config/source-scope.json'), 'utf8')));
  const excluded = document.plans.find(plan => !sourceAllowed(plan, sourceScope));
  if (excluded) throw new Error(`Independent club source cannot be loaded: ${excluded.url}`);
  return document.plans;
}

/**
 * Format a timestamp as the calendar date used by the discovery interface.
 * @param {Date|string|number} value Timestamp.
 * @return {string} YYYY-MM-DD date in America/New_York.
 */
export function localDay(value = new Date()) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: TIME_ZONE, year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(value));
}
